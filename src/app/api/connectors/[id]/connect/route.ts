export const dynamic = "force-dynamic";

const page = (origin: string, q: string) => NextResponse.redirect(`${origin}/app/connectors?${q}`, { status: 303 });

/** Start OAuth. The random state is stored server-side (hashed), bound to this user, single-use, 10 min. */
export async function GET(req: Request, { params }: { params: { id: string } }) {
  const url = new URL(req.url);
  const origin = url.origin;
  const a = await requireUser();
  if (!a) return NextResponse.redirect(`${origin}/login?next=/app/connectors`, { status: 303 });
  const c = CONNECTOR_ID.test(params.id) ? getConnector(params.id) : undefined;
  if (!c) return page(origin, "error=unknown");
  if (!isConfigured(c, process.env) || !connectMethods(c, process.env).oauth) return page(origin, `error=setup&connector=${c.id}`);
  if (!(await checkLimit(LIMITS.connect(a.user.id)))) return page(origin, `error=rate&connector=${c.id}`);
  try {
    const pkce = c.oauth?.pkce ? pkcePair() : undefined;
    const state = await createState({ userId: a.user.id, connectorId: c.id, codeVerifier: pkce?.verifier, returnTo: safeReturnTo(url.searchParams.get("return")) });
    return NextResponse.redirect(authorizeUrl(c, process.env, { redirectUri: `${origin}/api/connectors/${c.id}/callback`, state, codeChallenge: pkce?.challenge }), { status: 303 });
  } catch {
    return page(origin, `error=start&connector=${c.id}`);
  }
}

/** api_key connectors: { apiKey } is validated with a test call to the provider before it is saved. */
export async function POST(req: Request, { params }: { params: { id: string } }) {
  const a = await requireUser();
  if (!a) return unauthorized();
  const c = CONNECTOR_ID.test(params.id) ? getConnector(params.id) : undefined;
  if (!c) return notFound();
  if (!c.apiKey) return badRequest("This app connects with OAuth. Use the Connect button.");
  if (!isConfigured(c, process.env)) return json({ error: "This connector isn't set up on this server yet." }, 503);
  if (!(await checkLimit(LIMITS.connect(a.user.id)))) return tooMany();
  const body = await readJson(req);
  const key = typeof body?.apiKey === "string" ? body.apiKey.trim() : "";
  if (!key || key.length > 500) return badRequest(`Paste your ${c.apiKey.label}.`);
  let v: Awaited<ReturnType<NonNullable<typeof c.apiKey>["validate"]>>;
  try { v = await c.apiKey.validate(key, fetch); }
  catch (e) {
    // Messages are generated by us and redacted; the key itself is never echoed back.
    return json({ error: e instanceof ConnectorError ? e.message : `Couldn't verify the token with ${c.name}.` }, 400);
  }
  try {
    await saveConnection(a.user.id, c.id, { creds: { type: "api_key", access_token: key, meta: v.meta }, accountLabel: v.accountLabel, scopes: v.scopes ?? c.scopes });
  } catch { return json({ error: "Couldn't save the connection securely." }, 500); }
  await logActivity(a.db, a.user.id, { category: "connection", title: `Connected ${c.name}` });
  const resumed = await resumeTasksFor(a.db, a.user.id, c);
  return json({ ok: true, connector: c.id, accountLabel: v.accountLabel, resumedTasks: resumed });
}
